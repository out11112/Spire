"""Original act map generation, ported from the reference assembly.

Mirrors ``MegaCrit.Sts2.Core.Map``: ``StandardActMap``, ``MapPathPruning`` and
``MapPostProcessing``, plus the per-act room counts from
``MegaCrit.Sts2.Core.Models.Acts``. Checked against fixtures generated by the
shipping sts2.dll — see ``tools/refharness/README.md``.

Three things here are load-bearing and easy to get subtly wrong:

* ``StableShuffle`` **sorts** before shuffling, so the draw consumed depends on
  the sorted order of the input, not on the order the caller built it in.
* ``HashSet<MapPoint>`` enumerates in insertion order, and the order in which
  children are visited decides the path list, which decides the shuffle. Node
  sets are therefore modelled as insertion-ordered, free-list-reusing sets.
* Pruning and the three post-processing passes **move nodes**, so a coordinate
  is not an identity. Nodes are compared and hashed by object identity, exactly
  as the original's default reference equality does.
"""
from collections import deque
from enum import IntEnum
from math import inf as INF

from ...rng.mega_random import Rng

MAP_WIDTH = 7
MAX_ELITES_BEFORE_ASCENSION = 5
ELITE_ASCENSION_MULTIPLIER = 1.6


class MapPointType(IntEnum):
    Unassigned = 0
    Unknown = 1
    Shop = 2
    Treasure = 3
    RestSite = 4
    Monster = 5
    Elite = 6
    Boss = 7
    Ancient = 8


LOWER_RESTRICTIONS = frozenset({MapPointType.RestSite, MapPointType.Elite})
UPPER_RESTRICTIONS = frozenset({MapPointType.RestSite})
PARENT_CHILD_RESTRICTIONS = frozenset({
    MapPointType.Elite, MapPointType.RestSite, MapPointType.Treasure, MapPointType.Shop,
})
SIBLING_RESTRICTIONS = frozenset({
    MapPointType.RestSite, MapPointType.Monster, MapPointType.Unknown,
    MapPointType.Elite, MapPointType.Shop,
})


class RefSet:
    """A set with ``HashSet<MapPoint>`` enumeration order.

    The original walks its entry array in insertion order and reuses the most
    recently freed slot on the next insert. Node sets only gain members before
    pruning, so in practice this is insertion order — but the free list is
    modelled anyway, because losing it would silently change path order.

    Membership goes through a side dict rather than a scan: every add, discard
    and parent check hits it, and the scan made generation quadratic.
    """

    __slots__ = ('_slots', '_free', '_where')

    def __init__(self, items=()):
        self._slots = []
        self._free = []
        self._where = {}
        for item in items:
            self.add(item)

    def add(self, item):
        if item in self._where:
            return
        if self._free:
            index = self._free.pop()
            self._slots[index] = item
        else:
            index = len(self._slots)
            self._slots.append(item)
        self._where[item] = index

    def discard(self, item):
        index = self._where.pop(item, None)
        if index is None:
            return
        self._slots[index] = None
        self._free.append(index)

    def __contains__(self, item):
        return item in self._where

    def __iter__(self):
        return (slot for slot in self._slots if slot is not None)

    def __len__(self):
        return len(self._where)

    def __repr__(self):
        return f'RefSet({list(self)!r})'


class MapPoint:
    """``MapPoint``. Identity semantics throughout — coordinates are mutable."""

    __slots__ = ('col', 'row', 'type', 'can_be_modified', 'parents', 'children')

    def __init__(self, col, row):
        self.col = col
        self.row = row
        self.type = MapPointType.Unassigned
        self.can_be_modified = True
        self.parents = RefSet()
        self.children = RefSet()

    @property
    def coord(self):
        return (self.col, self.row)

    def add_child(self, child):
        self.children.add(child)
        child.parents.add(self)

    def remove_child(self, child):
        self.children.discard(child)
        child.parents.discard(self)

    def siblings(self):
        return [other for parent in self.parents for other in parent.children if other is not self]

    def __repr__(self):
        return f'Point[{self.col},{self.row} {self.type.name}]'


ACT_SPECS = {
    # Name -> (index, rooms, weak encounters)
    'Overgrowth': (0, 15, 3),
    'Underdocks': (0, 15, 3),
    'Hive': (1, 14, 2),
    'Glory': (2, 13, 2),
}
DEFAULT_ACTS = {'Overgrowth': 'Underdocks', 'Hive': None, 'Glory': None}
TWO_ACT_ONE_CHOICES = ('Overgrowth', 'Underdocks')


class MapPointTypeCounts:
    """``MapPointTypeCounts``. Elite and shop counts are fixed at A0."""

    __slots__ = ('unknowns', 'rests', 'elites', 'shops', 'ignore_rules')

    def __init__(self, unknown_count, rest_count, elite_count=None, shop_count=3, ignore_rules=frozenset()):
        self.unknowns = unknown_count
        self.rests = rest_count
        self.elites = MAX_ELITES_BEFORE_ASCENSION if elite_count is None else elite_count
        self.shops = shop_count
        self.ignore_rules = frozenset(ignore_rules)

    def should_ignore_rules(self, point_type):
        return point_type in self.ignore_rules


def standard_random_unknown_count(rng):
    """``MapPointTypeCounts.StandardRandomUnknownCount``."""
    return rng.next_gaussian_int(12, 1, 10, 14)


def act_point_type_counts(rng, act_name):
    """``ActModel.GetMapPointTypes``. Rest count is drawn *before* unknowns."""
    if act_name in ('Overgrowth', 'Underdocks'):
        rests = rng.next_gaussian_int(7, 1, 6, 7)
        unknowns = standard_random_unknown_count(rng)
    elif act_name == 'Hive':
        rests = rng.next_gaussian_int(6, 1, 6, 7)
        unknowns = standard_random_unknown_count(rng) - 1
    elif act_name == 'Glory':
        rests = rng.next_int_range(5, 7)
        unknowns = standard_random_unknown_count(rng) - 1
    else:
        raise KeyError(f'unknown act {act_name!r}')
    return MapPointTypeCounts(unknowns, rests)


def act_number_of_rooms(act_name, is_multiplayer):
    rooms = ACT_SPECS[act_name][1]
    return rooms - 1 if is_multiplayer else rooms


def unstable_shuffle(items, rng):
    """``ListExtensions.UnstableShuffle`` — descending Fisher-Yates in place."""
    return rng.shuffle(items)


def stable_shuffle(items, rng, key):
    """``ListExtensions.StableShuffle`` — sort, then shuffle the sorted list."""
    return rng.stable_shuffle(items, key)


def _coord_key(point):
    return (point.col, point.row)


def _at(grid, col, row):
    """Index the grid the way the original does: bounds are the array's own.

    The original throws here rather than returning null, so a coordinate that
    should not reach this call must fail loudly instead of wrapping.
    """
    if not 0 <= col < len(grid) or not 0 <= row < len(grid[0]):
        raise IndexError(f'grid coordinate out of range: ({col}, {row})')
    return grid[col][row]


class StandardActMap:
    """``StandardActMap`` — the map every normal act is built from."""

    def __init__(self, rng, act_name, is_multiplayer, replace_treasure_with_elites,
                 has_second_boss=False, point_counts=None, enable_pruning=True, ascension=0):
        self._map_length = act_number_of_rooms(act_name, is_multiplayer) + 1
        self.should_replace_treasure_with_elites = replace_treasure_with_elites
        self.grid = [[None] * self._map_length for _ in range(MAP_WIDTH)]
        self.rng = rng
        self.start_points = RefSet()
        self._counts = point_counts if point_counts is not None else act_point_type_counts(rng, act_name)
        if point_counts is None and ascension>=1:self._counts.elites=8

        self.boss = MapPoint(MAP_WIDTH // 2, self._map_length)
        self.starting = MapPoint(MAP_WIDTH // 2, 0)
        self.second_boss = MapPoint(MAP_WIDTH // 2, self._map_length + 1) if has_second_boss else None

        self._generate_map()
        self._assign_point_types()
        if enable_pruning:
            MapPathPruning.prune_and_repair(
                self.grid, self.start_points, self, self._counts, rng, self.is_valid_point_type)
        self.grid = MapPostProcessing.center_grid(self.grid)
        self.grid = MapPostProcessing.spread_adjacent_map_points(self.grid)
        self.grid = MapPostProcessing.straighten_paths(self.grid)

    # -- shape ------------------------------------------------------------

    def get_column_count(self):
        return len(self.grid)

    def get_row_count(self):
        return len(self.grid[0])

    def get_point(self, col, row):
        if (col, row) == (self.boss.col, self.boss.row):
            return self.boss
        if self.second_boss is not None and (col, row) == (self.second_boss.col, self.second_boss.row):
            return self.second_boss
        if (col, row) == (self.starting.col, self.starting.row):
            return self.starting
        if 0 <= col < len(self.grid) and 0 <= row < self._map_length:
            return self.grid[col][row]
        return None

    def get_or_create_point(self, col, row):
        point = self.get_point(col, row)
        if point is not None:
            return point
        point = MapPoint(col, row)
        self.grid[col][row] = point
        return point

    def get_all_map_points(self):
        for col in range(self.get_column_count()):
            for row in range(self._map_length):
                if self.grid[col][row] is not None:
                    yield self.grid[col][row]

    def points_in_row(self, row):
        if row < 0 or row >= self._map_length:
            return
        for col in range(self.get_column_count()):
            if self.grid[col][row] is not None:
                yield self.grid[col][row]

    def all_nodes_with_boss(self):
        yield from self.get_all_map_points()
        yield self.boss
        if self.second_boss is not None:
            yield self.second_boss
        yield self.starting

    # -- generation -------------------------------------------------------

    def _generate_map(self):
        for index in range(MAP_WIDTH):
            point = self.get_or_create_point(self.rng.next_int_range(0, MAP_WIDTH), 1)
            if index == 1:
                while point in self.start_points:
                    point = self.get_or_create_point(self.rng.next_int_range(0, MAP_WIDTH), 1)
            self.start_points.add(point)
            self._path_generate(point)

        for point in self.points_in_row(self.get_row_count() - 1):
            point.add_child(self.boss)
        if self.second_boss is not None:
            self.boss.add_child(self.second_boss)
        for point in self.points_in_row(1):
            self.starting.add_child(point)

    def _path_generate(self, starting_point):
        point = starting_point
        while point.row < self._map_length - 1:
            coord = self._generate_next_coord(point)
            child = self.get_or_create_point(*coord)
            point.add_child(child)
            point = child

    def _generate_next_coord(self, current):
        left = max(0, current.col - 1)
        right = min(current.col + 1, MAP_WIDTH - 1)
        columns = [-1, 0, 1]
        stable_shuffle(columns, self.rng, key=lambda value: value)
        for offset in columns:
            target = left if offset == -1 else current.col if offset == 0 else right
            if not self._has_invalid_crossover(current, target):
                return (target, current.row + 1)
        raise RuntimeError('Cannot find next node')

    def _has_invalid_crossover(self, current, target_col):
        delta = target_col - current.col
        if delta == 0 or delta == MAP_WIDTH:
            return False
        point = _at(self.grid, target_col, current.row)
        if point is None:
            return False
        for child in point.children:
            if child.col - point.col == -delta:
                return True
        return False

    # -- point types ------------------------------------------------------

    def _assign_point_types(self):
        for point in self.points_in_row(self.get_row_count() - 1):
            point.type = MapPointType.RestSite
            point.can_be_modified = False
        replacement = MapPointType.Elite if self.should_replace_treasure_with_elites else MapPointType.Treasure
        for point in self.points_in_row(self.get_row_count() - 7):
            point.type = replacement
            point.can_be_modified = False
        for point in self.points_in_row(1):
            point.type = MapPointType.Monster
            point.can_be_modified = False

        pending = deque()
        pending.extend([MapPointType.RestSite] * self._counts.rests)
        pending.extend([MapPointType.Shop] * self._counts.shops)
        pending.extend([MapPointType.Elite] * self._counts.elites)
        pending.extend([MapPointType.Unknown] * self._counts.unknowns)
        self._assign_remaining_types(pending)

        for point in self.get_all_map_points():
            if point.type == MapPointType.Unassigned:
                point.type = MapPointType.Monster

        self.boss.type = MapPointType.Boss
        self.starting.type = MapPointType.Ancient
        if self.second_boss is not None:
            self.second_boss.type = MapPointType.Boss

    def _assign_remaining_types(self, pending):
        for _ in range(3):
            if not pending:
                break
            candidates = [p for p in self.get_all_map_points() if p.type == MapPointType.Unassigned]
            stable_shuffle(candidates, self.rng, key=_coord_key)
            for point in candidates:
                if not pending:
                    break
                point.type = self._next_valid_type(pending, point)

    def _next_valid_type(self, pending, point):
        for _ in range(len(pending)):
            point_type = pending.popleft()
            if self._counts.should_ignore_rules(point_type):
                return point_type
            if self.is_valid_point_type(point_type, point):
                return point_type
            pending.append(point_type)
        return MapPointType.Unassigned

    def is_valid_point_type(self, point_type, point):
        return (self._valid_for_upper(point_type, point)
                and self._valid_for_lower(point_type, point)
                and self._valid_with_parents(point_type, point)
                and self._valid_with_children(point_type, point)
                and self._valid_with_siblings(point_type, point))

    def _valid_for_lower(self, point_type, point):
        if point.row < 6:
            return point_type not in LOWER_RESTRICTIONS
        return True

    def _valid_for_upper(self, point_type, point):
        if point.row >= self._map_length - 3:
            return point_type not in UPPER_RESTRICTIONS
        return True

    def _valid_with_parents(self, point_type, point):
        if point_type in PARENT_CHILD_RESTRICTIONS:
            neighbours = list(point.parents) + list(point.children)
            return not any(other.type == point_type for other in neighbours)
        return True

    def _valid_with_children(self, point_type, point):
        if point_type in PARENT_CHILD_RESTRICTIONS:
            return not any(child.type == point_type for child in point.children)
        return True

    def _valid_with_siblings(self, point_type, point):
        if point_type in SIBLING_RESTRICTIONS:
            return not any(other.type == point_type for other in point.siblings())
        return True


class SpoilsActMap:
    """``SpoilsActMap`` — the hourglass route the SpoilsMap card deals.

    Structurally unlike the standard map: every route is funnelled through a
    single mandatory treasure node, so the middle rows narrow to a point. It has
    no boss-side row of rest sites and no post-processing passes.
    """

    def __init__(self, rng, act_name, is_multiplayer, point_counts=None, ascension=0):
        self._map_length = act_number_of_rooms(act_name, is_multiplayer) + 1
        self.rng = rng
        self.grid = [[None] * self._map_length for _ in range(MAP_WIDTH)]
        self.start_points = RefSet()
        self._counts = point_counts if point_counts is not None else act_point_type_counts(rng, act_name)
        if point_counts is None and ascension>=1:self._counts.elites=8
        self._treasure_row = self._map_length - 7
        self.boss = MapPoint(MAP_WIDTH // 2, self._map_length)
        self.starting = MapPoint(MAP_WIDTH // 2, 0)
        self.second_boss = None

        self._generate_hourglass_map()
        self._assign_point_types()
        MapPathPruning.prune_and_repair(
            self.grid, self.start_points, self, self._counts, rng, self.is_valid_point_type)

    def get_column_count(self):
        return len(self.grid)

    def get_row_count(self):
        return self._map_length

    def get_point(self, col, row):
        if (col, row) == (self.boss.col, self.boss.row):
            return self.boss
        if (col, row) == (self.starting.col, self.starting.row):
            return self.starting
        if 0 <= col < len(self.grid) and 0 <= row < self._map_length:
            return self.grid[col][row]
        return None

    def get_or_create_point(self, col, row):
        """Note: unlike the standard map this does not consult the start or boss."""
        if 0 <= col < len(self.grid) and 0 <= row < self._map_length and self.grid[col][row] is not None:
            return self.grid[col][row]
        point = MapPoint(col, row)
        self.grid[col][row] = point
        return point

    def get_all_map_points(self):
        for col in range(self.get_column_count()):
            for row in range(self._map_length):
                if self.grid[col][row] is not None:
                    yield self.grid[col][row]

    def points_in_row(self, row):
        for col in range(self.get_column_count()):
            if self.grid[col][row] is not None:
                yield self.grid[col][row]

    def all_nodes_with_boss(self):
        yield from self.get_all_map_points()
        yield self.boss
        yield self.starting

    # -- generation -------------------------------------------------------

    def _generate_hourglass_map(self):
        centre = self.get_column_count() // 2
        if not 0 < self._treasure_row < self.get_row_count():
            raise ValueError('Treasure row is out of bounds for SpoilsActMap')

        for index in range(MAP_WIDTH):
            point = self.get_or_create_point(self.rng.next_int_range(0, MAP_WIDTH), 1)
            if index == 1:
                while point in self.start_points:
                    point = self.get_or_create_point(self.rng.next_int_range(0, MAP_WIDTH), 1)
            self.start_points.add(point)
            self._path_generate(point)

        treasure = self.get_or_create_point(centre, self._treasure_row)
        treasure.type = MapPointType.Treasure
        treasure.can_be_modified = False
        for point in list(self.points_in_row(self._treasure_row)):
            if point is not treasure:
                self._redirect_to_treasure(point, treasure)

        self._connect_row_to_boss()
        self._connect_row_to_start()

    def _path_generate(self, starting_point):
        point = starting_point
        while point.row < self._map_length - 1:
            coord = self._generate_next_coord(point)
            child = self.get_or_create_point(*coord)
            point.add_child(child)
            point = child

    def _allowed_columns_for_row(self, row):
        centre = self.get_column_count() // 2
        distance_to_treasure = abs(row - self._treasure_row)
        room_to_boss = self._map_length - 1 - row
        near_boss = min(centre, max(0, room_to_boss) + 1)
        span = min(centre, min(distance_to_treasure, near_boss))
        return max(0, centre - span), min(6, centre + span)

    def _build_centred_priority(self, current_col, centre_col):
        priority = []
        towards = 1 if centre_col > current_col else (-1 if centre_col < current_col else 0)
        if towards:
            priority.append(towards)
        priority.append(0)
        if towards and -towards not in priority:
            priority.append(-towards)
        for value in (-1, 1):
            if value not in priority:
                priority.append(value)
        return priority

    def _generate_next_coord(self, current):
        row = current.row + 1
        min_col, max_col = self._allowed_columns_for_row(row)
        centre = self.get_column_count() // 2
        distance_to_treasure = self._treasure_row - current.row
        if distance_to_treasure > 3 or distance_to_treasure <= 0:
            candidates = [-1, 0, 1]
            stable_shuffle(candidates, self.rng, key=lambda value: value)
        else:
            candidates = self._build_centred_priority(current.col, centre)

        for direction in candidates:
            target = self._next_column(current.col, direction)
            if target < min_col or target > max_col or self._has_invalid_crossover(current, target):
                continue
            point = self.get_point(target, row)
            joinable = (point is None or current in point.parents or len(point.parents) < 3)
            reachable = (current is self.starting or len(current.children) < 3
                         or (point is not None and point in current.children))
            if joinable and reachable:
                if abs(target - current.col) > 1:
                    raise RuntimeError(
                        f'Invalid step from ({current.col}, {current.row}) to column {target}')
                return (target, row)

        target = min(max(centre, min_col), max_col)
        if abs(target - current.col) > 1:
            step = 1 if target > current.col else -1
            target = min(max(current.col + step, min_col), max_col)
        if self._has_invalid_crossover(current, target):
            target = min(max(current.col, min_col), max_col)
        if abs(target - current.col) > 1:
            raise RuntimeError(
                f'Fallback step from ({current.col}, {current.row}) to column {target} exceeds adjacency')
        return (target, row)

    @staticmethod
    def _next_column(current_col, direction):
        if direction == -1:
            return max(0, current_col - 1)
        if direction == 1:
            return min(6, current_col + 1)
        return current_col

    def _has_invalid_crossover(self, current, target_col):
        delta = target_col - current.col
        if delta == 0:
            return False
        point = self.get_point(target_col, current.row)
        if point is None:
            return False
        return any(child.col - point.col == -delta for child in point.children)

    def _redirect_to_treasure(self, stray, treasure):
        for parent in list(stray.parents):
            parent.remove_child(stray)
            parent.add_child(treasure)
        for child in list(stray.children):
            stray.remove_child(child)
            treasure.add_child(child)
        self.grid[stray.col][stray.row] = None

    def _connect_row_to_boss(self):
        row = self.get_row_count() - 1
        for col in range(self.get_column_count()):
            point = self.grid[col][row]
            if point is not None and self.boss not in point.children:
                point.add_child(self.boss)

    def _connect_row_to_start(self):
        for col in range(self.get_column_count()):
            point = self.grid[col][1]
            if point is not None and point not in self.starting.children:
                self.starting.add_child(point)

    # -- point types ------------------------------------------------------

    def _assign_point_types(self):
        for point in self.points_in_row(self.get_row_count() - 1):
            point.type = MapPointType.RestSite
            point.can_be_modified = False
        for point in self.points_in_row(1):
            point.type = MapPointType.Monster
            point.can_be_modified = False

        pending = deque()
        pending.extend([MapPointType.RestSite] * self._counts.rests)
        pending.extend([MapPointType.Shop] * self._counts.shops)
        pending.extend([MapPointType.Elite] * self._counts.elites)
        pending.extend([MapPointType.Unknown] * self._counts.unknowns)
        self._assign_remaining_types(pending)

        for point in self.get_all_map_points():
            if point.type == MapPointType.Unassigned:
                point.type = MapPointType.Monster
        self.boss.type = MapPointType.Boss
        self.starting.type = MapPointType.Ancient

    def _assign_remaining_types(self, pending):
        for _ in range(3):
            if not pending:
                break
            candidates = [p for p in self.get_all_map_points()
                          if p is not self.boss and p is not self.starting
                          and p.type == MapPointType.Unassigned]
            stable_shuffle(candidates, self.rng, key=_coord_key)
            for point in candidates:
                if not pending:
                    break
                point_type = self._next_valid_type(pending, point)
                if point_type != MapPointType.Unassigned:
                    point.type = point_type

    def _next_valid_type(self, pending, point):
        if not pending:
            return MapPointType.Unassigned
        for _ in range(len(pending)):
            point_type = pending.popleft()
            if self._counts.should_ignore_rules(point_type) or self.is_valid_point_type(point_type, point):
                return point_type
            pending.append(point_type)
        return MapPointType.Unassigned

    def is_valid_point_type(self, point_type, point):
        return (self._valid_for_upper(point_type, point)
                and self._valid_for_lower(point_type, point)
                and self._valid_with_parents(point_type, point)
                and self._valid_with_children(point_type, point)
                and self._valid_with_siblings(point_type, point))

    def _valid_for_lower(self, point_type, point):
        if point.row < 6:
            return point_type not in LOWER_RESTRICTIONS
        return True

    def _valid_for_upper(self, point_type, point):
        if point.row >= self._map_length - 3:
            return point_type not in UPPER_RESTRICTIONS
        return True

    def _valid_with_parents(self, point_type, point):
        if point_type in PARENT_CHILD_RESTRICTIONS:
            neighbours = list(point.parents) + list(point.children)
            return not any(other.type == point_type for other in neighbours)
        return True

    def _valid_with_children(self, point_type, point):
        if point_type in PARENT_CHILD_RESTRICTIONS:
            return not any(child.type == point_type for child in point.children)
        return True

    def _valid_with_siblings(self, point_type, point):
        if point_type in SIBLING_RESTRICTIONS:
            return not any(other.type == point_type for other in point.siblings())
        return True


class GoldenPathActMap:
    """``GoldenPathActMap`` — a fixed single-column route. Consumes no randomness."""

    DEFAULT_POINT_TYPES = (
        MapPointType.Monster, MapPointType.Unknown, MapPointType.Monster,
        MapPointType.RestSite, MapPointType.Monster, MapPointType.RestSite,
        MapPointType.Unknown, MapPointType.Treasure, MapPointType.Unknown,
        MapPointType.Treasure, MapPointType.Unknown, MapPointType.Shop,
        MapPointType.Elite, MapPointType.RestSite, MapPointType.Elite,
        MapPointType.RestSite,
    )
    MIDDLE = 3

    def __init__(self, is_multiplayer=False):
        types = list(self.DEFAULT_POINT_TYPES)
        if is_multiplayer:
            del types[2]
        rows = len(types) + 1
        self._map_length = rows
        self.grid = [[None] * rows for _ in range(MAP_WIDTH)]
        self.start_points = RefSet()
        self.boss = MapPoint(MAP_WIDTH // 2, rows)
        self.boss.type = MapPointType.Boss
        self.starting = MapPoint(MAP_WIDTH // 2, 0)
        self.starting.type = MapPointType.Ancient
        self.second_boss = None

        for index, point_type in enumerate(types):
            point = MapPoint(self.MIDDLE, index + 1)
            self.grid[self.MIDDLE][index + 1] = point
            point.type = point_type
            if index > 0:
                self.grid[self.MIDDLE][index].add_child(point)
        self.start_points.add(self.grid[self.MIDDLE][1])
        self.grid[self.MIDDLE][rows - 1].add_child(self.boss)
        self.starting.add_child(self.grid[self.MIDDLE][1])

    def get_column_count(self):
        return len(self.grid)

    def get_row_count(self):
        return self._map_length

    def get_point(self, col, row):
        if (col, row) == (self.boss.col, self.boss.row):
            return self.boss
        if (col, row) == (self.starting.col, self.starting.row):
            return self.starting
        if 0 <= col < len(self.grid) and 0 <= row < self._map_length:
            return self.grid[col][row]
        return None

    def get_all_map_points(self):
        for col in range(self.get_column_count()):
            for row in range(self._map_length):
                if self.grid[col][row] is not None:
                    yield self.grid[col][row]

    def points_in_row(self, row):
        for col in range(self.get_column_count()):
            if self.grid[col][row] is not None:
                yield self.grid[col][row]

    def all_nodes_with_boss(self):
        yield from self.get_all_map_points()
        yield self.boss
        yield self.starting


class MapPathPruning:
    """``MapPathPruning`` — collapse duplicate route shapes, then repair counts."""

    MAX_ITERATIONS = 50

    @staticmethod
    def prune_and_repair(grid, start_points, map_, counts, rng, is_valid_point_type):
        for _ in range(3):
            MapPathPruning.prune_duplicate_segments(grid, start_points, map_.starting, rng)
            if not MapPathPruning.repair_pruned_point_types(map_, counts, rng, is_valid_point_type):
                break

    @staticmethod
    def repair_pruned_point_types(map_, counts, rng, is_valid_point_type):
        # ``flag |= …`` on booleans does not short-circuit, so all four run.
        changed = MapPathPruning._repair_point_type(
            map_, MapPointType.Shop, counts.shops, rng, is_valid_point_type)
        changed |= MapPathPruning._repair_point_type(
            map_, MapPointType.Elite, counts.elites, rng, is_valid_point_type)
        changed |= MapPathPruning._repair_point_type(
            map_, MapPointType.RestSite, counts.rests, rng, is_valid_point_type)
        return changed | MapPathPruning._repair_point_type(
            map_, MapPointType.Unknown, counts.unknowns, rng, is_valid_point_type)

    @staticmethod
    def _repair_point_type(map_, point_type, target_count, rng, is_valid_point_type):
        current = sum(1 for point in map_.get_all_map_points() if point.type == point_type)
        needed = target_count - current
        if needed <= 0:
            return False
        candidates = [p for p in map_.get_all_map_points()
                      if p.type == MapPointType.Monster and p.can_be_modified]
        stable_shuffle(candidates, rng, key=_coord_key)
        changed = False
        for point in candidates:
            if needed == 0:
                break
            if is_valid_point_type(point_type, point):
                point.type = point_type
                needed -= 1
                changed = True
        return changed

    @staticmethod
    def prune_duplicate_segments(grid, start_points, starting_point, rng):
        iterations = 0
        matches = MapPathPruning.find_matching_segments(starting_point)
        while MapPathPruning._prune_paths(grid, start_points, matches, rng):
            iterations += 1
            if iterations > MapPathPruning.MAX_ITERATIONS:
                raise RuntimeError(f'Unable to prune matching segments in {iterations} iterations')
            matches = MapPathPruning.find_matching_segments(starting_point)

    @staticmethod
    def find_matching_segments(starting_point):
        grouped = {}
        for path in MapPathPruning.find_all_paths(starting_point):
            MapPathPruning._add_segments_to_dictionary(path, grouped)
        # .NET uses a SortedDictionary with ordinal string ordering; duplicate
        # groups are then visited in ascending key order.
        return [grouped[key] for key in sorted(grouped) if len(grouped[key]) > 1]

    @staticmethod
    def find_all_paths(current):
        if current.type == MapPointType.Boss:
            return [[current]]
        paths = []
        for child in current.children:
            for tail in MapPathPruning.find_all_paths(child):
                paths.append([current] + tail)
        return paths

    @staticmethod
    def _add_segments_to_dictionary(path, grouped):
        """Add this path's candidate segments to ``grouped``, keyed the way the original does.

        The key is the endpoint coordinates plus the point types in order. Every
        key for this path is a contiguous run of the type string, so the type
        part is cut out of one precomputed string rather than rebuilt per
        candidate — that alone was most of map generation's cost.

        Each stored entry carries the identity set of its interior nodes, so the
        "do these two segments share an interior node" test is a set intersection
        instead of a Python loop over the pair.

        Bucketing candidates by endpoints first, to skip the string work for
        segments that are alone in their bucket, was tried and measured: the
        bookkeeping costs more than it saves here, because the segment shapes
        repeat often enough that few buckets end up with a single entry.
        """
        type_ids = [int(point.type) for point in path]
        joined = ','.join(str(value) for value in type_ids)
        offsets = []
        position = 0
        for value in type_ids:
            offsets.append(position)
            position += len(str(value)) + 1
        offsets.append(position)

        parents = [len(point.parents) for point in path]
        children = [len(point.children) for point in path]

        for i in range(len(path) - 1):
            # ``IsValidSegmentStart``: a single child only counts on the start row.
            if children[i] <= 1 and path[i].row != 0:
                continue
            first = path[i]
            head = (f'{first.row}-' if first.row == 0 else f'{first.col},{first.row}-')
            interior = set()
            for j in range(2, len(path) - i):
                index = i + j
                # The interior of ``path[i:index + 1]`` is ``path[i + 1:index]``.
                interior.add(id(path[index - 1]))
                if parents[index] < 2:
                    continue
                end = path[index]
                key = f'{head}{end.col},{end.row}-{joined[offsets[i]:offsets[index + 1] - 1]}'
                bucket = grouped.get(key)
                if bucket is None:
                    grouped[key] = [(path[i:index + 1], frozenset(interior))]
                elif not any(interior & seen for _, seen in bucket):
                    bucket.append((path[i:index + 1], frozenset(interior)))

    @staticmethod
    def _prune_paths(grid, start_points, matching_segments, rng):
        for matches in matching_segments:
            unstable_shuffle(matches, rng)
            if MapPathPruning._prune_all_but_last(grid, start_points, matches) != 0:
                return True
            if MapPathPruning._break_relationship_in_any(matches):
                return True
        return False

    @staticmethod
    def _prune_all_but_last(grid, start_points, matches):
        pruned = 0
        for segment, _ in matches:
            if pruned == len(matches) - 1:
                return pruned
            if MapPathPruning._prune_segment(grid, start_points, segment):
                pruned += 1
        return pruned

    @staticmethod
    def _prune_segment(grid, start_points, segment):
        pruned = False
        for i in range(len(segment) - 1):
            point = segment[i]
            if not MapPathPruning._is_in_map(grid, point):
                return True
            if (len(point.children) > 1 or len(point.parents) > 1
                    or any(len(parent.children) == 1 and not MapPathPruning._is_removed(grid, parent)
                           for parent in point.parents)):
                continue
            remainder = segment[i:]
            if any(len(other.children) > 1 and len(other.parents) == 1 for other in remainder):
                continue
            if len(segment[-1].parents) == 1:
                return False
            if any(len(child.parents) == 1 for child in point.children
                   if not any(child is kept for kept in segment)):
                continue
            MapPathPruning._remove_point(grid, start_points, point)
            pruned = True
        return pruned

    @staticmethod
    def _remove_point(grid, start_points, point):
        grid[point.col][point.row] = None
        start_points.discard(point)
        for child in list(point.children):
            point.remove_child(child)
        for parent in list(point.parents):
            parent.remove_child(point)

    @staticmethod
    def _is_in_map(grid, point):
        if _at(grid, point.col, point.row) is None and point.type != MapPointType.Ancient:
            return point.type == MapPointType.Boss
        return True

    @staticmethod
    def _is_removed(grid, point):
        return _at(grid, point.col, point.row) is None

    @staticmethod
    def _break_relationship_in_any(matches):
        for segment, _ in matches:
            if MapPathPruning._break_relationship_in_segment(segment):
                return True
        return False

    @staticmethod
    def _break_relationship_in_segment(segment):
        changed = False
        for i in range(len(segment) - 1):
            point = segment[i]
            if len(point.children) >= 2:
                following = segment[i + 1]
                if len(following.parents) != 1:
                    point.remove_child(following)
                    changed = True
        return changed


class MapPostProcessing:
    """``MapPostProcessing`` — recentre, spread and straighten the finished grid."""

    @staticmethod
    def _column_empty(grid, col):
        return all(grid[col][row] is None for row in range(len(grid[col])))

    @staticmethod
    def center_grid(grid):
        width, height = len(grid), len(grid[0])
        left_empty = MapPostProcessing._column_empty(grid, 0) and MapPostProcessing._column_empty(grid, 1)
        right_empty = (MapPostProcessing._column_empty(grid, width - 1)
                       and MapPostProcessing._column_empty(grid, width - 2))
        if left_empty and not right_empty:
            shift = -1
        elif not left_empty and right_empty:
            shift = 1
        else:
            return grid
        if shift > 0:
            columns = range(width - 1, -1, -1)
        else:
            columns = range(width)
        for row in range(height):
            for col in columns:
                point = grid[col][row]
                grid[col][row] = None
                target = col + shift
                if 0 <= target < width:
                    grid[target][row] = point
                    if point is not None:
                        point.col = target
        return grid

    @staticmethod
    def straighten_paths(grid):
        width, height = len(grid), len(grid[0])
        for row in range(height):
            for col in range(width):
                point = grid[col][row]
                if point is None or len(point.parents) != 1 or len(point.children) != 1:
                    continue
                parent = next(iter(point.parents))
                child = next(iter(point.children))
                concave_left = point.col < child.col and point.col < parent.col
                concave_right = point.col > child.col and point.col > parent.col
                if concave_left and col < width - 1:
                    target = col + 1
                    if grid[target][row] is not None:
                        continue
                    point.col = target
                    grid[col][row] = None
                    grid[target][row] = point
                if concave_right and col > 0:
                    target = col - 1
                    if grid[target][row] is None:
                        point.col = target
                        grid[col][row] = None
                        grid[target][row] = point
        return grid

    @staticmethod
    def _neighbour_positions(col, total):
        return {col + offset for offset in (-1, 0, 1) if 0 <= col + offset < total}

    @staticmethod
    def _allowed_positions(point, total):
        allowed = set(range(total))
        for parent in point.parents:
            allowed &= MapPostProcessing._neighbour_positions(parent.col, total)
        for child in point.children:
            allowed &= MapPostProcessing._neighbour_positions(child.col, total)
        return allowed

    @staticmethod
    def _compute_gap(candidate_col, row_nodes, current):
        """``Math.Min`` over the other nodes in the row, or ``int.MaxValue``.

        The sentinel is a real value here, not a "no answer" marker: a lone node
        in its row outranks every finite gap, so it must compare as larger.
        """
        best = INF
        for node in row_nodes:
            if node is not current:
                best = min(best, abs(candidate_col - node.col))
        return best

    @staticmethod
    def spread_adjacent_map_points(grid):
        width, height = len(grid), len(grid[0])
        for row in range(height):
            nodes = [grid[col][row] for col in range(width) if grid[col][row] is not None]
            moved = True
            while moved:
                moved = False
                for node in nodes:
                    col = node.col
                    best_col, best_gap = col, MapPostProcessing._compute_gap(col, nodes, node)
                    for candidate in sorted(MapPostProcessing._allowed_positions(node, width)):
                        if candidate == col:
                            continue
                        if grid[candidate][row] is not None and grid[candidate][row] is not node:
                            continue
                        gap = MapPostProcessing._compute_gap(candidate, nodes, node)
                        if gap > best_gap:
                            best_col, best_gap = candidate, gap
                    if best_col != col:
                        grid[col][row] = None
                        grid[best_col][row] = node
                        node.col = best_col
                        moved = True
        return grid
