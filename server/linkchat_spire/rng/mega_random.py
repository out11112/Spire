"""Original random number system, ported from the reference assembly.

Everything here mirrors ``MegaCrit.Sts2.Core.Random``, ``Helpers.SeedHelper`` and
``Helpers.StringHelper.GetDeterministicHashCode`` from Slay the Spire 2 v0.111.0
(sts2.dll sha256 0861bfa1df347538d932f22d580e75420f08082792eb914e53b4882764acdbe9)
and is checked against fixtures generated by that assembly, not against a
hand-transcribed summary of it.

Two behaviours are deliberately odd and must not be "fixed":

* ``MegaRandom.next`` reduces a double into the range instead of rejecting
  samples, so it is very slightly biased for large ranges. The original does
  this; matching it matters more than being uniform.
* ``next_gaussian_int`` rounds half to even and retries out-of-range draws,
  while ``next_gaussian_double`` clamps into ``[0, 1]`` before scaling by
  ``min``/``max``. They are not two views of one function.
"""
from functools import lru_cache
from math import cos, inf, log, pi, sin, sqrt, trunc
from struct import pack, unpack
from time import time

MASK64 = (1 << 64) - 1
INT_MIN = -2147483648
INT_MAX = 2147483647
UINT_MAX = 4294967295
ULONG_MAX = (1 << 64) - 1

_GAMMA = 11400714819323198485
_MIX_A = 13787848793156543929
_MIX_B = 10723151780598845931

# SeedHelper
SEED_ALPHABET = '0123456789ABCDEFGHJKLMNPQRSTUVWXYZ'
SEED_DEFAULT_LENGTH = 12

# 2 ** -53 and 2 ** -24, the two scale factors the original multiplies by.
_DOUBLE_INCR = 1.1102230246251565e-16
_FLOAT_INCR = 5.9604645e-08


def rotl(value, distance):
    return ((value << distance) | (value >> (64 - distance))) & MASK64


def f32(value):
    """Round a Python float to the nearest IEEE-754 binary32, as C# would."""
    try:
        return unpack('<f', pack('<f', value))[0]
    except OverflowError:
        return inf if value > 0 else -inf


def as_int32(value):
    """Truncate a Python int the way an unchecked C# ``(int)`` cast would."""
    return ((int(value) + 0x80000000) & 0xFFFFFFFF) - 0x80000000


def as_uint32(value):
    return int(value) & 0xFFFFFFFF


def _round64(accumulator, lane):
    return (rotl((accumulator + lane * _XX_P2) & MASK64, 31) * _XX_P1) & MASK64


_XX_P1 = 11400714785074694791
_XX_P2 = 14029467366897019727
_XX_P3 = 1609587929392839161
_XX_P4 = 9650029242287828579
_XX_P5 = 2870177450012600261


def xxhash64(data, seed=0):
    """``System.IO.Hashing.XxHash64.HashToUInt64`` — standard xxHash64."""
    length = len(data)
    offset = 0
    if length >= 32:
        v1 = (seed + _XX_P1 + _XX_P2) & MASK64
        v2 = (seed + _XX_P2) & MASK64
        v3 = seed & MASK64
        v4 = (seed - _XX_P1) & MASK64
        while offset <= length - 32:
            v1 = _round64(v1, int.from_bytes(data[offset:offset + 8], 'little'))
            v2 = _round64(v2, int.from_bytes(data[offset + 8:offset + 16], 'little'))
            v3 = _round64(v3, int.from_bytes(data[offset + 16:offset + 24], 'little'))
            v4 = _round64(v4, int.from_bytes(data[offset + 24:offset + 32], 'little'))
            offset += 32
        digest = (rotl(v1, 1) + rotl(v2, 7) + rotl(v3, 12) + rotl(v4, 18)) & MASK64
        for lane in (v1, v2, v3, v4):
            digest ^= _round64(0, lane)
            digest = (digest * _XX_P1 + _XX_P4) & MASK64
    else:
        digest = (seed + _XX_P5) & MASK64

    digest = (digest + length) & MASK64

    while offset + 8 <= length:
        digest ^= _round64(0, int.from_bytes(data[offset:offset + 8], 'little'))
        digest = (rotl(digest, 27) * _XX_P1 + _XX_P4) & MASK64
        offset += 8
    if offset + 4 <= length:
        digest ^= (int.from_bytes(data[offset:offset + 4], 'little') * _XX_P1) & MASK64
        digest = (rotl(digest, 23) * _XX_P2 + _XX_P3) & MASK64
        offset += 4
    while offset < length:
        digest ^= (data[offset] * _XX_P5) & MASK64
        digest = (rotl(digest, 11) * _XX_P1) & MASK64
        offset += 1

    digest ^= digest >> 33
    digest = (digest * _XX_P2) & MASK64
    digest ^= digest >> 29
    digest = (digest * _XX_P3) & MASK64
    digest ^= digest >> 32
    return digest


@lru_cache(maxsize=4096)
def deterministic_hash(text):
    """``StringHelper.GetDeterministicHashCode`` — XxHash64 of the UTF-8 bytes."""
    return xxhash64(text.encode('utf-8'), 0)


def deterministic_hash_old(text):
    """The pre-1.0 32-bit hash, still reachable through legacy ``old`` seeds."""
    first = second = 352654597
    for index in range(0, len(text), 2):
        first = (((first << 5) + first) & 0xFFFFFFFF) ^ ord(text[index])
        if index == len(text) - 1:
            break
        second = (((second << 5) + second) & 0xFFFFFFFF) ^ ord(text[index + 1])
    return as_int32((first + second * 1566083941) & 0xFFFFFFFF)


def canonicalize_seed(seed):
    """``SeedHelper.CanonicalizeSeed``: uppercase, then fold the two look-alikes.

    Applied to what a player types, so ``o0i1`` and ``0011`` are one seed.
    """
    return seed.upper().replace('O', '0').replace('I', '1').strip()


_CHAOTIC = None


def chaotic():
    """``Rng.Chaotic`` — one process-wide stream, seeded once from the clock.

    It has to be a single advancing instance, as in the original: seeding a new
    stream per call would hand out the same "random" seed to every run created
    in the same second, because the clock only has second resolution.
    """
    global _CHAOTIC
    if _CHAOTIC is None:
        _CHAOTIC = Rng(int(time()))
    return _CHAOTIC


def generate_seed(rng=None, length=SEED_DEFAULT_LENGTH):
    """``SeedHelper.GetRandomSeed`` for a run created without one.

    The original redraws a seed that trips its profanity list. That list runs to
    576 entries and has no bearing on reproducibility — the generated seed is
    reported to the player either way — so it is not carried over. A blank seed
    is meant to be unique, not to reproduce a particular draw.
    """
    source = rng if rng is not None else chaotic()
    return ''.join(source.next_item(SEED_ALPHABET) for _ in range(length))


_ALNUM = frozenset('abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789')
_UPPER = frozenset('ABCDEFGHIJKLMNOPQRSTUVWXYZ')


def snake_case(text):
    """``StringHelper.SnakeCase`` for its ``([A-Za-z0-9]|\\G(?!^))([A-Z])`` rule.

    Python's :mod:`re` has no ``\\G``, so the scan is spelled out: a match is
    either a word character followed by a capital, or a capital that sits
    immediately after the previous match.
    """
    text = text.strip()
    out = []
    written = 0
    previous_end = 0
    scan = 0
    end = len(text)
    while scan < end:
        match = None
        for index in range(scan, end):
            if text[index] in _ALNUM and index + 1 < end and text[index + 1] in _UPPER:
                match = (index, index + 2, text[index], text[index + 1])
                break
            if index == previous_end and index != 0 and text[index] in _UPPER:
                match = (index, index + 1, '', text[index])
                break
        if match is None:
            break
        start, stop, head, tail = match
        out.append(text[written:start])
        out.append(head + '_' + tail)
        written = stop
        previous_end = stop
        scan = stop
    out.append(text[written:])
    return ''.join(out).lower()


class MegaRandom:
    """``MegaCrit.Sts2.Core.Random.MegaRandom`` — splitmix64-seeded xoshiro256**."""

    __slots__ = ('state',)

    def __init__(self, seed=0):
        self.state = None
        self.reinitialise(seed)

    def reinitialise(self, seed):
        """Seed the four lanes from four successive splitmix64 draws."""
        value = seed & MASK64
        lanes = []
        for _ in range(4):
            value = (value + _GAMMA) & MASK64
            mixed = value
            mixed = ((mixed ^ (mixed >> 30)) * _MIX_A) & MASK64
            mixed = ((mixed ^ (mixed >> 27)) * _MIX_B) & MASK64
            lanes.append(mixed ^ (mixed >> 31))
        self.state = lanes

    def reinitialise_from_state(self, state):
        if len(state) != 4:
            raise ValueError('MegaRandom holds four 64-bit lanes.')
        self.state = [int(lane) & MASK64 for lane in state]

    def next_ulong(self):
        s0, s1, s2, s3 = self.state
        result = (rotl((s1 * 5) & MASK64, 7) * 9) & MASK64
        shifted = (s1 << 17) & MASK64
        s2 ^= s0
        s3 ^= s1
        s1 ^= s2
        s0 ^= s3
        s2 ^= shifted
        s3 = rotl(s3, 45)
        self.state = [s0, s1, s2, s3]
        return result

    def next_double(self):
        return (self.next_ulong() >> 11) * _DOUBLE_INCR

    def next_float(self):
        return f32((self.next_ulong() >> 40) * _FLOAT_INCR)

    def next_int32(self):
        return as_int32(self.next_ulong() >> 33)

    def next_uint(self):
        return as_uint32(self.next_ulong())

    def next_bool(self):
        return (self.next_ulong() & 0x8000000000000000) != 0

    def next(self, max_value):
        if max_value < 1:
            raise ValueError('maxValue must be > 0')
        return self._next_inner(max_value)

    def next_range(self, min_value, max_value):
        if min_value >= max_value:
            raise ValueError('maxValue must be > minValue')
        span = max_value - min_value
        if span <= INT_MAX:
            return self._next_inner(span) + min_value
        return as_int32(self._next_long_inner(span) + min_value)

    def _next_inner(self, max_value):
        return as_int32(trunc(self.next_double() * max_value))

    def _next_long_inner(self, max_value):
        return trunc(self.next_double() * max_value)


class Rng:
    """``MegaCrit.Sts2.Core.Random.Rng`` — a counter plus a MegaRandom lane.

    The counter is part of the saved state and of the comparison contract: a
    divergent counter means the two runs consumed different numbers of draws,
    which is exactly the failure this port is meant to catch.
    """

    __slots__ = ('counter', 'random')

    def __init__(self, seed=0):
        self.counter = 0
        self.random = MegaRandom(seed)

    @classmethod
    def from_state(cls, counter, state):
        rng = cls(0)
        rng.counter = counter
        rng.random.reinitialise_from_state(state)
        return rng

    # -- draws ------------------------------------------------------------

    def next_bool(self):
        self.counter += 1
        return self.random.next(2) == 0

    def next_int(self, max_exclusive=INT_MAX):
        self.counter += 1
        return self.random.next(max_exclusive)

    def next_int_range(self, min_inclusive, max_exclusive):
        if min_inclusive >= max_exclusive:
            raise ValueError('Minimum must be lower than maximum.')
        self.counter += 1
        return self.random.next_range(min_inclusive, max_exclusive)

    def next_unsigned_int(self, min_inclusive=0, max_exclusive=UINT_MAX):
        if min_inclusive >= max_exclusive:
            raise ValueError('Minimum must be lower than maximum.')
        self.counter += 1
        span = as_uint32(max_exclusive - min_inclusive)
        return min_inclusive + as_uint32(trunc(self.random.next_double() * span))

    def next_unsigned_long(self, min_inclusive=0, max_exclusive=ULONG_MAX):
        if max_exclusive == ULONG_MAX:
            if min_inclusive == 0:
                return self.next_unsigned_long_raw()
            raise ValueError('Minimum must be lower than maximum.')
        if min_inclusive >= max_exclusive:
            raise ValueError('Minimum must be lower than maximum.')
        self.counter += 1
        span = max_exclusive - min_inclusive
        return min_inclusive + int(trunc(self.random.next_double() * span))

    def next_unsigned_long_raw(self):
        self.counter += 1
        return self.random.next_ulong()

    def next_float(self, min_value=0.0, max_value=1.0):
        if min_value > max_value:
            raise ValueError('Minimum must not be higher than maximum.')
        self.counter += 1
        span = f32(f32(max_value) - f32(min_value))
        return f32(self.random.next_double() * span + f32(min_value))

    def next_double(self, min_value=0.0, max_value=1.0):
        if min_value > max_value:
            raise ValueError('Minimum must not be higher than maximum.')
        self.counter += 1
        return self.random.next_double() * (max_value - min_value) + min_value

    def next_gaussian_float(self, mean=0.0, std_dev=1.0, min_value=0.0, max_value=1.0):
        return f32(self.next_gaussian_double(mean, std_dev, min_value, max_value))

    def next_gaussian_double(self, mean=0.0, std_dev=1.0, min_value=0.0, max_value=1.0):
        if min_value > max_value:
            raise ValueError('Minimum must not be higher than maximum.')
        if mean < 0.0 or mean > 1.0:
            raise ValueError('Mean must be within [0, 1].')
        while True:
            first = 1.0 - self.next_double()
            second = 1.0 - self.next_double()
            radius = sqrt(-2.0 * log(first))
            angle = pi * 2.0 * second
            value = mean + radius * cos(angle) * std_dev
            if not (value < 0.0 or value > 1.0):
                break
        return value * (max_value - min_value) + min_value

    def next_gaussian_int(self, mean, std_dev, min_value, max_value):
        if min_value > max_value:
            raise ValueError('Minimum must not be higher than maximum.')
        if mean < min_value or mean > max_value:
            raise ValueError('Mean must be within [min, max].')
        while True:
            first = 1.0 - self.next_double()
            second = 1.0 - self.next_double()
            radius = sqrt(-2.0 * log(first)) * sin(pi * 2.0 * second)
            result = round(mean + std_dev * radius)
            if min_value <= result <= max_value:
                return result

    # -- collections ------------------------------------------------------

    def next_item(self, items):
        items = list(items)
        if not items:
            return None
        return items[self.next_int_range(0, len(items))]

    def weighted_next_item(self, items, weight_fetcher, fallback=None):
        return self.weighted_pick(self.next_float(), items, weight_fetcher, fallback)

    @staticmethod
    def weighted_pick(roll, items, weight_fetcher, fallback=None):
        """Weights accumulate in binary32; the original never widens to double."""
        total = f32(0.0)
        for item in items:
            total = f32(total + f32(weight_fetcher(item)))
        remaining = f32(f32(roll) * total)
        for item in items:
            remaining = f32(remaining - f32(weight_fetcher(item)))
            if remaining <= 0.0:
                return item
        return fallback

    def shuffle(self, items):
        """Descending Fisher-Yates. Shuffles in place, like the original."""
        for index in range(len(items) - 1, 0, -1):
            other = self.next_int(index + 1)
            items[index], items[other] = items[other], items[index]
        return items

    def stable_shuffle(self, items, key):
        """``ListExtensions.StableShuffle`` — sort first, then shuffle the sorted list.

        The sort is what makes it "stable": the draw consumed depends on the
        sorted order, not on how the caller happened to arrange the input. Card
        piles sort by ``(ModelId, upgrade level)``.

        The sort itself is ``List<T>.Sort``, which is *not* stable: items with
        equal keys (two plain Strikes, one of them enchanted) come out in the
        order .NET's introsort leaves them, so it is reproduced exactly rather
        than approximated with Python's stable ``sorted``.
        """
        dotnet_sort(items, key)
        return self.shuffle(items)

    # -- persistence ------------------------------------------------------

    def to_serializable(self):
        return {
            'counter': self.counter,
            's0': self.random.state[0],
            's1': self.random.state[1],
            's2': self.random.state[2],
            's3': self.random.state[3],
        }

    @classmethod
    def from_serializable(cls, saved):
        return cls.from_state(
            saved['counter'],
            [saved['s0'], saved['s1'], saved['s2'], saved['s3']],
        )


def dotnet_sort(items, key):
    """``List<T>.Sort()`` — .NET's introspective sort, in place.

    Ported from ``ArraySortHelper<T>``: insertion sort up to 16 items (sizes 2
    and 3 by compare-and-swap), otherwise median-of-three quicksort that falls
    back to heapsort past ``2 * (log2(n) + 1)`` levels. Only the order of items
    with equal keys differs from ``sorted``; that order is part of the result.
    """
    keys = [key(item) for item in items]
    order = list(range(len(items)))

    def less(a, b):
        return keys[a] < keys[b]

    def swap_if_greater(lo, i, j):
        if i != j and less(order[lo + j], order[lo + i]):
            order[lo + i], order[lo + j] = order[lo + j], order[lo + i]

    def insertion_sort(lo, n):
        for i in range(n - 1):
            t = order[lo + i + 1]
            j = i
            while j >= 0 and less(t, order[lo + j]):
                order[lo + j + 1] = order[lo + j]
                j -= 1
            order[lo + j + 1] = t

    def down_heap(lo, i, n):
        d = order[lo + i - 1]
        while i <= n >> 1:
            child = 2 * i
            if child < n and less(order[lo + child - 1], order[lo + child]):
                child += 1
            if not less(d, order[lo + child - 1]):
                break
            order[lo + i - 1] = order[lo + child - 1]
            i = child
        order[lo + i - 1] = d

    def heap_sort(lo, n):
        for i in range(n >> 1, 0, -1):
            down_heap(lo, i, n)
        for i in range(n, 1, -1):
            order[lo], order[lo + i - 1] = order[lo + i - 1], order[lo]
            down_heap(lo, 1, i - 1)

    def partition(lo, n):
        hi = n - 1
        middle = hi >> 1
        swap_if_greater(lo, 0, middle)
        swap_if_greater(lo, 0, hi)
        swap_if_greater(lo, middle, hi)
        pivot = order[lo + middle]
        order[lo + middle], order[lo + hi - 1] = order[lo + hi - 1], order[lo + middle]
        left, right = 0, hi - 1
        while left < right:
            # ``while (left < nextToLast && keys[++left] < pivot);`` and its mirror:
            # bound first, then step, then compare.
            while left < hi - 1:
                left += 1
                if not less(order[lo + left], pivot):
                    break
            while right > 0:
                right -= 1
                if not less(pivot, order[lo + right]):
                    break
            if left >= right:
                break
            order[lo + left], order[lo + right] = order[lo + right], order[lo + left]
        if left != hi - 1:
            order[lo + left], order[lo + hi - 1] = order[lo + hi - 1], order[lo + left]
        return left

    def intro_sort(lo, n, depth):
        while n > 1:
            if n <= 16:
                if n == 2:
                    swap_if_greater(lo, 0, 1)
                elif n == 3:
                    swap_if_greater(lo, 0, 1)
                    swap_if_greater(lo, 0, 2)
                    swap_if_greater(lo, 1, 2)
                else:
                    insertion_sort(lo, n)
                return
            if depth == 0:
                heap_sort(lo, n)
                return
            depth -= 1
            p = partition(lo, n)
            intro_sort(lo + p + 1, n - p - 1, depth)
            n = p

    if len(items) > 1:
        intro_sort(0, len(items), 2 * (len(items).bit_length()))
    items[:] = [items[i] for i in order]
    return items


