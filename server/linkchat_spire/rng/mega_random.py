def run_seed(seed_string):
    """``RunRngSet(string seed)``: the run's 64-bit seed, legacy prefix included."""
    if seed_string.startswith('old'):
        return as_uint32(deterministic_hash_old(seed_string[len('old'):]))
    return deterministic_hash(seed_string)


class RngSet:
    """A named family of streams, each derived from ``seed + hash(name)``."""

    __slots__ = ('seed', 'streams')

    def __init__(self, seeds, names):
        self.seed = seeds
        self.streams = {
            key: Rng((seeds + deterministic_hash(name)) & MASK64) for key, name in names
        }

    def get(self, key):
        return self.streams[key]

    def __getitem__(self, key):
        return self.streams[key]

    def to_serializable(self):
        return {key: rng.to_serializable() for key, rng in self.streams.items()}

    def load_serializable(self, saved):
        for key, state in saved.items():
            self.streams[key] = Rng.from_serializable(state)


class RunRngSet(RngSet):
    """``RunRngSet`` — one stream per ``RunRngType``."""

    def __init__(self, seed_string):
        self.string_seed = seed_string
        super().__init__(run_seed(seed_string), RUN_RNG_STREAMS)

    @classmethod
    def from_serializable(cls, seed_string, saved):
        """Rebuild a set and restore every stream's counter and lanes.

        Only the seed string is needed to lay the streams out; the saved states
        then replace what that seed would have produced, so a reload continues
        instead of restarting.
        """
        instance = cls(seed_string)
        instance.load_serializable(saved)
        return instance


class PlayerRngSet(RngSet):
    """``PlayerRngSet`` — one stream per ``PlayerRngType``, seeded per player."""

    def __init__(self, seed):
        super().__init__(seed & MASK64, PLAYER_RNG_STREAMS)

    @classmethod
    def from_serializable(cls, seed, saved):
        instance = cls(seed)
        instance.load_serializable(saved)
        return instance
